def ticker_universe():
    """
    ticker_universe returns the engine's ticker list, read from experiment_main so the two cannot drift apart

    Falls back to a copy only if experiment_main cannot be imported, which happens if its
    dependencies are not installed yet. The fallback is asserted against the real list by
    tests/test_synthetic_data.py, so a silent divergence is caught.

    Returns:
        list of bare ticker symbols, lowercase, in the engine's order
    """
    try:
        sys.path.insert(0, HERE)
        from experiment_main import TICKER_FILES

        return [name.split(".")[0] for name in TICKER_FILES]
    except Exception as why:
        print(f"[synthetic] NOTE could not import experiment_main ({why}); using the "
              "built-in ticker list. This is only a problem if the engine's TICKER_FILES "
              "has changed.")
        return list(FALLBACK_TICKERS)


def trading_days(months: int, end: str = "2025-02-06"):
    """
    trading_days builds a plausible US equity trading calendar: weekdays minus the federal holidays

    This is deliberately approximate. The real NYSE calendar differs -- it closes on Good
    Friday, which is not a federal holiday, and it has early closes that the federal
    calendar knows nothing about. None of that matters here: the engine needs a calendar
    with gaps in it, not the right one. `build_near_close_daily` derives the session end
    POSITIONALLY (the last bar of whatever bars a day has), so it handles a short day
    without being told which days are short.

    Arguments:
        months -- how many months of history to produce

    Keyword Arguments:
        end -- the last trading date, matching the real data's end so the two are swappable (default: {"2025-02-06"})

    Returns:
        DatetimeIndex of trading dates, ascending
    """
    end_ts = pd.Timestamp(end)
    start_ts = end_ts - pd.DateOffset(months=months)
    weekdays = pd.bdate_range(start_ts, end_ts)
    holidays = USFederalHolidayCalendar().holidays(start=start_ts, end=end_ts)
    return weekdays.difference(holidays)


def session_stamps(day, open_time, close_time, minutes):
    """
    session_stamps gives the tz-naive UTC timestamps of one day's bars, derived from exchange-local session times

    The engine stores bars as tz-naive UTC and reads them back as UTC via
    `to_exchange_time`, so the conversion has to happen HERE and has to respect DST. A
    fixed UTC offset would drift an hour twice a year and push bars outside the
    09:30-16:00 window that `filter_regular_session` applies in local time -- which would
    silently change which bars the regular-session guardrail run sees.

    Arguments:
        day -- the exchange-local trading date
        open_time -- first bar's local time, "HH:MM"
        close_time -- last bar's local time, "HH:MM"
        minutes -- bar width in minutes

    Returns:
        DatetimeIndex of tz-naive UTC timestamps for that session
    """
    local_open = pd.Timestamp(f"{day.date()} {open_time}").tz_localize(EXCHANGE_TZ)
    local_close = pd.Timestamp(f"{day.date()} {close_time}").tz_localize(EXCHANGE_TZ)
    local = pd.date_range(local_open, local_close, freq=f"{minutes}min")
    return local.tz_convert("UTC").tz_localize(None)


def daily_closes(n_days, rng, start_price):
    """
    daily_closes draws one geometric Brownian motion path, one close per trading day

    Arguments:
        n_days -- number of trading days
        rng -- a seeded numpy Generator
        start_price -- the first close

    Returns:
        ndarray of closes, length n_days
    """
    # ~20% annualised vol and a small positive drift: a plausible-LOOKING equity path. The
    # numbers are arbitrary and chosen only so the MACD has something to cross over.
    daily_vol = 0.20 / np.sqrt(252)
    daily_drift = 0.06 / 252
    shocks = rng.normal(daily_drift - 0.5 * daily_vol**2, daily_vol, n_days)
    return start_price * np.exp(np.cumsum(shocks))


def intraday_bridge(open_price, close_price, n_bars, rng):
    """
    intraday_bridge draws an intraday path that starts near open_price and ENDS EXACTLY at close_price

    A plain random walk per day would end wherever it happened to end, and the daily file's
    close would then disagree with the intraday bars for the same date. `read_official_closes`
    takes the execution price from the daily file while the signal comes from the intraday
    bars, so that disagreement would put a fictional gap between decision and execution on
    every single day -- a systematic bias in exactly the quantity the paper measures.

    A Brownian bridge fixes both ends. The path is pinned, so the last intraday price IS the
    official close, and the two files are consistent by construction rather than by luck.

    Arguments:
        open_price -- where the session starts
        close_price -- where the session must end
        n_bars -- number of bars in the session
        rng -- a seeded numpy Generator

    Returns:
        ndarray of n_bars + 1 prices, the bar boundaries, with path[0] == open_price and path[-1] == close_price
    """
    # work in logs so the bridge is multiplicative and prices stay positive
    log_open, log_close = np.log(open_price), np.log(close_price)
    steps = rng.normal(0.0, 0.20 / np.sqrt(252 * n_bars), n_bars)
    walk = np.concatenate([[0.0], np.cumsum(steps)])
    # subtract the straight line through the walk's own endpoints, then add the line
    # through the required endpoints: standard Brownian bridge construction
    fraction = np.linspace(0.0, 1.0, n_bars + 1)
    bridge = walk - fraction * walk[-1]
    return np.exp(log_open + bridge + fraction * (log_close - log_open))


def bars_from_path(path, rng):
    """
    bars_from_path turns a price path into OHLC bars, one bar per step

    high and low are pushed just outside the bar's own open/close by a small random amount,
    which is what a real bar looks like and, more practically, keeps high >= max(open,
    close) >= min(open, close) >= low true so that nothing downstream divides by a zero
    range.

    Arguments:
        path -- ndarray of n+1 bar boundaries
        rng -- a seeded numpy Generator

    Returns:
        (opens, highs, lows, closes) as float ndarrays of length n
    """
    opens, closes = path[:-1], path[1:]
    upper = np.maximum(opens, closes)
    lower = np.minimum(opens, closes)
    wiggle = np.abs(rng.normal(0.0, 0.0008, len(opens)))
    return opens, upper * (1 + wiggle), lower * (1 - wiggle), closes


def frame_for(ticker, stamps, opens, highs, lows, closes, per, rng):
    """
    frame_for assembles one timeframe's dataframe in the exact vendor layout the engine reads

    Arguments:
        ticker -- bare symbol, lowercase
        stamps -- tz-naive UTC DatetimeIndex, one per bar
        opens, highs, lows, closes -- float arrays
        per -- the <PER> value: 1 for daily, 5 for 5-minute, 60 for hourly, matching what the
               real download writes
        rng -- a seeded numpy Generator, for volume and trade counts

    Returns:
        DataFrame with COLUMNS, ready for to_csv
    """
    stamps = pd.DatetimeIndex(stamps)
    count = len(stamps)
    volume = np.round(rng.lognormal(10.5, 0.8, count), 1)
    return pd.DataFrame({
        "<TICKER>": [f"{ticker.upper()}.US"] * count,
        "<PER>": [per] * count,
        # zero-padded strings, which is how the vendor writes them and what make_index
        # concatenates: an int here loses the leading zero on a 05:00 stamp and the
        # resulting "20200207 50000" does not parse
        "<DATE>": stamps.strftime("%Y%m%d"),
        "<TIME>": stamps.strftime("%H%M%S"),
        "<OPEN>": np.round(opens, 4),
        "<HIGH>": np.round(highs, 4),
        "<LOW>": np.round(lows, 4),
        "<CLOSE>": np.round(closes, 4),
        "<VOL>": volume,
        "<OPENINT>": [0] * count,
        # a volume-weighted average has to sit inside the bar, so take a point between the
        # low and the high rather than an independent draw
        "<VWAP>": np.round(lows + (highs - lows) * rng.uniform(0.2, 0.8, count), 4),
        "<TRANSACTIONS>": np.maximum(1, (volume / 100).astype(int)),
    })[COLUMNS]


def aggregate_to_hour(five_minute):
    """
    aggregate_to_hour rolls the 5-minute bars up into hourly bars

    Derived from the 5-minute bars rather than drawn separately, so the two timeframes
    cannot tell different stories about the same session -- the hourly run and the daily
    run would otherwise be looking at different securities with the same name.

    Arguments:
        five_minute -- the 5-minute dataframe in vendor layout

    Returns:
        the hourly dataframe in vendor layout
    """
    working = five_minute.copy()
    stamps = pd.to_datetime(
        working["<DATE>"] + working["<TIME>"], format="%Y%m%d%H%M%S"
    )
    working.index = stamps
    grouped = working.resample("1h").agg({
        "<OPEN>": "first", "<HIGH>": "max", "<LOW>": "min",
        "<CLOSE>": "last", "<VOL>": "sum", "<TRANSACTIONS>": "sum",
        "<VWAP>": "mean", "<TICKER>": "first",
    }).dropna(subset=["<OPEN>"])
    out = pd.DataFrame({
        "<TICKER>": grouped["<TICKER>"],
        "<PER>": 60,
        "<DATE>": grouped.index.strftime("%Y%m%d"),
        "<TIME>": grouped.index.strftime("%H%M%S"),
        "<OPEN>": grouped["<OPEN>"], "<HIGH>": grouped["<HIGH>"],
        "<LOW>": grouped["<LOW>"], "<CLOSE>": grouped["<CLOSE>"],
        "<VOL>": grouped["<VOL>"], "<OPENINT>": 0,
        "<VWAP>": np.round(grouped["<VWAP>"], 4),
        "<TRANSACTIONS>": grouped["<TRANSACTIONS>"].astype(int),
    })[COLUMNS]
    return out.reset_index(drop=True)


def build_ticker(ticker, days, seed, open_time, close_time):
    """
    build_ticker generates all three timeframes for one ticker from a single price path

    Arguments:
        ticker -- bare symbol, lowercase
        days -- the trading calendar
        seed -- this ticker's seed, so a rerun reproduces it exactly
        open_time -- session open, exchange local "HH:MM"
        close_time -- session close, exchange local "HH:MM"

    Returns:
        {"1_day": df, "1_hour": df, "5_minute": df}
    """
    rng = np.random.default_rng(seed)
    # a spread of starting prices across tickers, so the panel is not 32 copies of one
    # price level -- risk_per_trade sizing is in currency, so the level matters
    start_price = float(rng.uniform(25.0, 420.0))
    closes = daily_closes(len(days), rng, start_price)

    five_frames, daily_rows = [], []
    previous_close = start_price
    for position, day in enumerate(days):
        stamps = session_stamps(day, open_time, close_time, 5)
        n_bars = len(stamps) - 1
        if n_bars < 2:
            continue
        # the session opens with an overnight gap off the previous close, then the bridge
        # carries it to today's official close
        session_open = previous_close * float(np.exp(rng.normal(0.0, 0.004)))
        path = intraday_bridge(session_open, closes[position], n_bars, rng)
        opens, highs, lows, bar_closes = bars_from_path(path, rng)
        five_frames.append(
            frame_for(ticker, stamps[:-1], opens, highs, lows, bar_closes, 5, rng)
        )
        # the daily bar's own open/high/low come from the session, and its close is the
        # same number the bridge was pinned to -- which is the consistency that makes
        # read_official_closes agree with the intraday bars
        daily_rows.append((day, opens[0], highs.max(), lows.min(), closes[position]))
        previous_close = closes[position]

    five_minute = pd.concat(five_frames, ignore_index=True)

    # daily bars are stamped at exchange-local midnight, which is what the vendor does and
    # why the real files show 050000 in winter and 040000 in summer
    daily_stamps = pd.DatetimeIndex([
        pd.Timestamp(f"{row[0].date()} 00:00").tz_localize(EXCHANGE_TZ)
        .tz_convert("UTC").tz_localize(None)
        for row in daily_rows
    ])
    daily = frame_for(
        ticker, daily_stamps,
        np.array([r[1] for r in daily_rows]), np.array([r[2] for r in daily_rows]),
        np.array([r[3] for r in daily_rows]), np.array([r[4] for r in daily_rows]),
        1, np.random.default_rng(seed + 1),
    )

    return {
        "1_day": daily,
        "1_hour": aggregate_to_hour(five_minute),
        "5_minute": five_minute,
    }


def existing_real_data(root, timeframes):
    """
    existing_real_data reports which target folders already hold data this script did not write

    Arguments:
        root -- the data/stocks root
        timeframes -- folder names about to be written

    Returns:
        list of folders that contain .txt files but no synthetic marker
    """
    clashes = []
    for timeframe in timeframes:
        folder = os.path.join(root, timeframe)
        if not os.path.isdir(folder):
            continue
        has_data = any(name.endswith(".txt") for name in os.listdir(folder))
        marked = os.path.exists(os.path.join(folder, MARKER_NAME))
        if has_data and not marked:
            clashes.append(folder)
    return clashes


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate SYNTHETIC price data so experiment_main.py runs after a "
                    "clone. The output is random numbers, not market data, and no result "
                    "computed from it means anything.",
    )
    parser.add_argument("--tickers", type=int, default=4,
                        help="how many tickers from the engine's universe (default: 4)")
    parser.add_argument("--all-tickers", action="store_true",
                        help="generate all 32; large and slow, and only needed to "
                             "exercise the cross-sectional bootstrap arm")
    parser.add_argument("--months", type=int, default=42,
                        help="months of history. The daily run needs 24 before its first "
                             "walk-forward window exists, then one more per 3 months, so "
                             "42 gives 7 (default: 42)")
    parser.add_argument("--seed", type=int, default=20260101,
                        help="master seed; a rerun with the same seed is identical")
    parser.add_argument("--out", default=os.path.join(HERE, "data", "stocks"),
                        help="where to write the timeframe folders")
    parser.add_argument("--session-open", default="09:00",
                        help="first bar, exchange local. The default reaches a little "
                             "either side of 09:30-16:00 so the regular-session guardrail "
                             "run has bars to exclude (default: 09:00)")
    parser.add_argument("--session-close", default="16:30",
                        help="last bar, exchange local (default: 16:30)")
    parser.add_argument("--force", action="store_true",
                        help="overwrite data folders this script did not create. Without "
                             "it, real vendor data is never touched.")
    args = parser.parse_args(argv)

    timeframes = ["1_day", "1_hour", "5_minute"]
    universe = ticker_universe()
    chosen = universe if args.all_tickers else universe[: args.tickers]
    if not chosen:
        parser.error("--tickers must be at least 1")

    if args.months < 24:
        print(f"[synthetic] WARNING --months {args.months} is below 24. The daily branch "
              "uses time_value=12, so one window needs 12 months to choose a config and "
              "12 to validate it. The daily run will complete having produced NOTHING, "
              "which is not a bug.")

    clashes = existing_real_data(args.out, timeframes)
    if clashes and not args.force:
        print("[synthetic] REFUSING TO WRITE. These folders already contain data that "
              "this script did not generate:")
        for folder in clashes:
            print(f"             {folder}")
        print("           If that is real vendor data, it is not replaceable and this "
              "script will not overwrite it.\n"
              "           Move it aside, write elsewhere with --out, or pass --force if "
              "you are sure.")
        return 1

    print(f"[synthetic] {len(chosen)} tickers, {args.months} months, seed {args.seed}")
    print(f"[synthetic] session {args.session_open}-{args.session_close} exchange local")
    days = trading_days(args.months)
    print(f"[synthetic] {len(days)} trading days, "
          f"{days[0].date()} to {days[-1].date()}")
    daily_windows = 1 + (args.months - 24) // 3 if args.months >= 24 else 0
    print(f"[synthetic] the daily run will produce about {daily_windows} walk-forward "
          f"window(s) per config")

    for timeframe in timeframes:
        os.makedirs(os.path.join(args.out, timeframe), exist_ok=True)

    totals = {timeframe: 0 for timeframe in timeframes}
    for position, ticker in enumerate(chosen):
        frames = build_ticker(
            ticker, days, args.seed + position * 1000,
            args.session_open, args.session_close,
        )
        for timeframe, frame in frames.items():
            target = os.path.join(args.out, timeframe, f"{ticker}.us.txt")
            frame.to_csv(target, index=False)
            totals[timeframe] += len(frame)
        print(f"  {ticker:6} "
              + "  ".join(f"{tf}={len(frames[tf]):>7,}" for tf in timeframes))

    written = pd.Timestamp.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    for timeframe in timeframes:
        with open(os.path.join(args.out, timeframe, MARKER_NAME), "w") as handle:
            handle.write(MARKER_TEXT.format(
                seed=args.seed, tickers=", ".join(chosen), months=args.months,
                open_time=args.session_open, close_time=args.session_close,
                written=written,
            ))

    print()
    print("=" * 78)
    print("  THIS DATA IS SYNTHETIC. IT IS NOT MARKET DATA.")
    print()
    print("  Every price is a draw from a geometric Brownian motion. These files do not")
    print("  correspond to any real security, and NO NUMBER COMPUTED FROM THEM HAS ANY")
    print("  ECONOMIC MEANING. They exist only to show that the code runs.")
    print()
    print("  To reproduce the paper's results you need the real vendor data:")
    print("      python download_polygon.py --api-key YOUR_POLYGON_KEY")
    print("=" * 78)
    print()
    for timeframe in timeframes:
        print(f"  {timeframe:10} {totals[timeframe]:>10,} rows across "
              f"{len(chosen)} files")
    print()
    print("  Next:")
    print("      python experiment_main.py --timeframe 1_day --balance 20000 --sig 1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
